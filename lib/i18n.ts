/** Translate a key; falls back to English, then to the key itself. */
export function translate(lang: Lang, key: StringKey | (string & {})): string {
  const t = (l: Lang) => (TABLES[l] as Record<string, string | undefined>)[key];
  return t(lang) ?? t("en") ?? key;
}

/** Add/override strings at runtime-safe module level (for other workers' feature strings). */
export function registerStrings(lang: Lang, strings: Record<string, string>) {
  Object.assign(TABLES[lang] as Record<string, string>, strings);
}

