/** Map a lead's preferred_language (e.g. "Tamil") to a supported Lang, else "en". */
export function langFromName(name?: string): Lang {
  const n = (name ?? "").toLowerCase();
  if (n.startsWith("hin")) return "hi";
  if (n.startsWith("tam")) return "ta";
  if (n.startsWith("mar")) return "mr";
  return "en";
}

